#!/usr/bin/env python3
"""
test_polynomial_calibration_recovery.py

Integration tests for the detector → polynomial fit → config → calibrator pipeline.

Uses synthetic calibration images generated by generate_synthetic_calibration.py.
Tests both dotboard and ChArUco detector paths with model_type="polynomial".

Verifies:
  - Detectors succeed with model_type="polynomial"
  - Polynomial coefficients are saved to config.yaml
  - PolynomialVectorCalibrator can load from config and calibrate points
  - Config round-trip: known calibration points recover correct world positions

Usage:
    pytest unit-tests/test_polynomial_calibration_recovery.py -v
"""

