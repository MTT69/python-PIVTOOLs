@pytest.fixture(scope="module")
def dotboard_polynomial_result(ground_truth):
    """Run dotboard detector with model_type='polynomial'."""
    if not DOTBOARD_DIR.exists():
        pytest.skip("Dotboard images not found")

    from pivtools_gui.calibration.calibration_planar.planar_calibration_production import (
        MultiViewCalibrator,
    )

    persist_dir = UNIT_DIR / "test_output" / "polynomial_dotboard"
    # Clean previous run to avoid stale images / detection files
    if persist_dir.exists():
        shutil.rmtree(persist_dir)
    persist_dir.mkdir(parents=True, exist_ok=True)
    img_dir = persist_dir / "images"
    img_dir.mkdir(exist_ok=True)

    # Polynomial calibration uses a single datum image (the board on the
    # laser sheet). Unlike pinhole, we are NOT building a multi-view
    # camera model — just fitting pixel↔world mapping for one plane.
    first_image = sorted(DOTBOARD_DIR.glob("calib*.png"))[0]
    shutil.copy2(first_image, img_dir / first_image.name)

    # Create a config so the detector can save polynomial params.
    # calibration_sources + image_format are required by
    # build_calibration_camera_path used in _get_camera_input_dir.
    config_path = persist_dir / "config.yaml"
    config_dict = {
        "paths": {"base_paths": [str(persist_dir)]},
        "calibration": {
            "dotboard": {"dt": 0.001},
            "calibration_sources": [str(img_dir)],
            "image_format": "calib%05d.png",
        },
    }
    with open(config_path, "w") as f:
        yaml.dump(config_dict, f)

    reload_config()
    cfg = Config(path=str(config_path))

    calibrator = MultiViewCalibrator(
        source_dir=str(img_dir),
        base_dir=str(persist_dir),
        camera_count=1,
        file_pattern="calib%05d.png",
        pattern_cols=DOT_COLS,
        pattern_rows=DOT_ROWS,
        dot_spacing_mm=DOT_SPACING_MM,
        asymmetric=False,
        model_type="polynomial",
        config=cfg,
    )

    result = calibrator.process_single_camera(1, save_visualizations=True)
    assert result["success"], f"Dotboard polynomial calibration failed: {result.get('error')}"
    result["_persist_dir"] = persist_dir
    result["_config_path"] = config_path
    return result


