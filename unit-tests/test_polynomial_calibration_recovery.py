class TestCrossDetectorConsistency:
    """Verify dotboard and ChArUco polynomial paths produce similar results."""

    def test_mm_per_pixel_agreement(self, dotboard_polynomial_result, charuco_polynomial_result):
        """Both detectors should estimate similar mm_per_pixel."""
        mpp_dot = dotboard_polynomial_result["mm_per_pixel"]
        mpp_cha = charuco_polynomial_result["mm_per_pixel"]

        # Polynomial uses single datum image — different board types with
        # different random perspectives produce moderate scale variation.
        # Allow 35% (wider than pinhole multi-view which constrains better).
        rel_diff = abs(mpp_dot - mpp_cha) / max(mpp_dot, mpp_cha)
        assert rel_diff < 0.35, (
            f"mm_per_pixel disagrees: dotboard={mpp_dot:.6f}, charuco={mpp_cha:.6f} "
            f"(rel_diff={rel_diff:.3f})"
        )

    def test_image_centre_calibration_agreement(
        self, dotboard_polynomial_result, charuco_polynomial_result, ground_truth
    ):
        """Both paths should give similar physical coordinates for image centre."""
        results = []
        for result in [dotboard_polynomial_result, charuco_polynomial_result]:
            config_path = result["_config_path"]
            persist_dir = result["_persist_dir"]
            cfg = Config(path=str(config_path))

            cal = PolynomialVectorCalibrator(
                base_dir=str(persist_dir), camera_num=1, config=cfg,
            )

            gt_cam = ground_truth["camera_matrix"]
            x_raw = gt_cam[0, 2]
            y_raw = gt_cam[1, 2]
            x_uncal = np.array([x_raw + 1.0])
            y_uncal = np.array([cal.image_height - y_raw])

            x_mm, y_mm = cal.calibrate_coordinates(x_uncal, y_uncal)
            results.append((x_mm[0], y_mm[0]))

        # Polynomial uses single datum image from different boards with
        # different random perspectives. Allow 60mm — the boards are
        # centred differently in the field of view.
        dx = abs(results[0][0] - results[1][0])
        dy = abs(results[0][1] - results[1][1])
        assert dx < 60.0, f"x_mm disagrees by {dx:.2f}mm at image centre"
        assert dy < 60.0, f"y_mm disagrees by {dy:.2f}mm at image centre"


