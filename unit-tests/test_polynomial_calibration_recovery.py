class TestDiagnosticFigures:
    """Generate diagnostic plots when --make-figures is passed."""

    def test_make_figures(
        self, dotboard_polynomial_result, charuco_polynomial_result,
        ground_truth, make_figures,
    ):
        if not make_figures:
            pytest.skip("Pass --make-figures to generate diagnostic plots")

        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        out_dir = Path(__file__).resolve().parent / "test_output"
        out_dir.mkdir(exist_ok=True)

        K = ground_truth["camera_matrix"]
        fx = K[0, 0]
        img_w = int(K[0, 2] * 2)
        dist_coeffs = np.zeros(5)

        fig, axes = plt.subplots(1, 2, figsize=(16, 7))

        for ax, (label, result, grid_fn) in zip(axes, [
            ("Dotboard", dotboard_polynomial_result, self._dotboard_grid),
            ("ChArUco", charuco_polynomial_result, self._charuco_grid),
        ]):
            config_path = result["_config_path"]
            persist_dir = result["_persist_dir"]
            cfg = Config(path=str(config_path))
            cal = PolynomialVectorCalibrator(
                base_dir=str(persist_dir), camera_num=1, config=cfg,
            )

            board_centre, board_w, fill_range, world_pts_mm, rvec, tvec = grid_fn(
                K, fx, img_w,
            )

            xs, ys, errs = [], [], []
            for x_world_mm, y_world_mm, obj_pt_m in world_pts_mm:
                obj_3d = np.array([[[obj_pt_m[0], obj_pt_m[1], 0.0]]], dtype=np.float64)
                proj, _ = cv2.projectPoints(obj_3d, rvec, tvec, K, dist_coeffs)
                px, py = proj[0, 0]

                x_uncal = np.array([px + 1.0])
                y_uncal = np.array([cal.image_height - py])
                x_mm, y_mm = cal.calibrate_coordinates(x_uncal, y_uncal)

                err_x = abs(x_mm[0] - x_world_mm)
                err_y = abs(y_mm[0] - (-y_world_mm))
                err = np.sqrt(err_x**2 + err_y**2)

                xs.append(x_world_mm)
                ys.append(y_world_mm)
                errs.append(err)

            sc = ax.scatter(xs, ys, c=errs, cmap="hot", s=40, vmin=0,
                           vmax=max(0.5, max(errs)))
            plt.colorbar(sc, ax=ax, label="Round-trip error (mm)")
            ax.set_xlabel("Board x (mm)")
            ax.set_ylabel("Board y (mm)")
            ax.set_title(f"{label} — max err: {max(errs):.3f} mm")
            ax.set_aspect("equal")

        plt.suptitle("Polynomial Round-Trip Spatial Error", fontsize=14, fontweight="bold")
        plt.tight_layout()

        out_path = out_dir / "polynomial_roundtrip_spatial.png"
        plt.savefig(out_path, dpi=150, bbox_inches="tight")
        plt.close(fig)
        print(f"\n  Spatial error figure saved: {out_path}")

    @staticmethod
    def _dotboard_grid(K, fx, img_w):
        board_w = (DOT_COLS - 1) * DOT_SPACING_MM / 1000.0
        board_h = (DOT_ROWS - 1) * DOT_SPACING_MM / 1000.0
        board_centre = np.array([board_w / 2, board_h / 2, 0])
        poses = make_poses(
            10, board_centre, fx, img_w, board_w,
            fill_fraction_range=(0.80, 0.55),
        )
        rvec, tvec = poses[0]

        pts = []
        for col in range(DOT_COLS):
            for row in range(DOT_ROWS):
                x_mm = col * DOT_SPACING_MM
                y_mm = row * DOT_SPACING_MM
                pts.append((x_mm, y_mm, (col * DOT_SPACING_MM / 1000.0,
                                          row * DOT_SPACING_MM / 1000.0)))
        return board_centre, board_w, (0.80, 0.55), pts, rvec, tvec

    @staticmethod
    def _charuco_grid(K, fx, img_w):
        board_w = SQUARES_H * SQUARE_SIZE
        board_h = SQUARES_V * SQUARE_SIZE
        board_centre = np.array([board_w / 2, board_h / 2, 0])
        poses = make_poses(
            10, board_centre, fx, img_w, board_w,
            fill_fraction_range=(0.85, 0.65),
        )
        rvec, tvec = poses[0]
        sq_mm = SQUARE_SIZE * 1000.0

        pts = []
        for col in range(1, SQUARES_H):
            for row in range(1, SQUARES_V):
                x_mm = col * sq_mm
                y_mm = row * sq_mm
                pts.append((x_mm, y_mm, (col * SQUARE_SIZE, row * SQUARE_SIZE)))
        return board_centre, board_w, (0.85, 0.65), pts, rvec, tvec
