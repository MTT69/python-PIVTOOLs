# ChArUco parameters (must match generator)
SQUARES_H = 10
SQUARES_V = 7
SQUARE_SIZE = 0.030  # metres
MARKER_RATIO = 0.5
ARUCO_DICT = "DICT_4X4_1000"


def _skip_if_no_synth_data():
    if not GT_PATH.exists():
        pytest.skip(
            f"Synthetic calibration data not found at {SYNTH_DIR}. "
            "Run: python pivtools_cli/generate_synthetic_dotboard.py"
        )


