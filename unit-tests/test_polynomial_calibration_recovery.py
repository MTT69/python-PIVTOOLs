class TestDotboardPolynomial:
    """Verify dotboard detector succeeds with model_type='polynomial'."""

    def test_detection_succeeds(self, dotboard_polynomial_result):
        assert dotboard_polynomial_result["success"]
        assert dotboard_polynomial_result["model_type"] == "polynomial"

    def test_rms_error_low(self, dotboard_polynomial_result):
        rms = dotboard_polynomial_result["rms_error"]
        assert rms < 1.0, f"RMS fit error {rms:.4f} px too high"

    def test_mm_per_pixel_reasonable(self, dotboard_polynomial_result, ground_truth):
        """mm_per_pixel should be within 10% of ground truth scale."""
        mpp = dotboard_polynomial_result["mm_per_pixel"]
        # Compute expected scale from focal length and dot spacing
        gt_fx = ground_truth["camera_matrix"][0, 0]
        expected_mpp = DOT_SPACING_MM / (DOT_SPACING_MM / (DOT_SPACING_MM * gt_fx / 1000.0))
        # Just check it's physically reasonable (0.01 to 10 mm/px)
        assert 0.01 < mpp < 10.0, f"mm_per_pixel={mpp} out of reasonable range"

    def test_config_polynomial_params_written(self, dotboard_polynomial_result):
        """Config should have polynomial params for camera 1."""
        config_path = dotboard_polynomial_result["_config_path"]
        cfg = Config(path=str(config_path))
        cam_params = cfg.get_polynomial_camera_params(1)

        assert cam_params, "No polynomial camera params found in config"
        assert "origin" in cam_params
        assert "normalisation" in cam_params
        assert "mm_per_pixel" in cam_params
        assert "coefficients_x" in cam_params
        assert "coefficients_y" in cam_params
        assert "image_height" in cam_params
        assert len(cam_params["coefficients_x"]) == 10
        assert len(cam_params["coefficients_y"]) == 10
        assert cfg.polynomial_calibration.get("dt") == 0.001
        assert cfg.data["calibration"]["active"] == "polynomial"

    def test_config_round_trip_calibrate_point(self, dotboard_polynomial_result, ground_truth):
        """Load calibrator from config, calibrate known grid points, verify accuracy.

        This closes the seam: detector → fit → save_to_config → Config reload →
        PolynomialVectorCalibrator → calibrate_coordinates.

        Uses the ground truth camera model to project known dotboard grid
        points to pixel coordinates, converts to uncalibrated convention,
        runs through the polynomial calibrator, and verifies the output
        matches the known world coordinates within 1mm.
        """
        config_path = dotboard_polynomial_result["_config_path"]
        persist_dir = dotboard_polynomial_result["_persist_dir"]
        cfg = Config(path=str(config_path))

        cal = PolynomialVectorCalibrator(
            base_dir=str(persist_dir), camera_num=1, config=cfg,
        )

        # Recompute the exact poses used to generate the dotboard images.
        # make_poses is deterministic (seed=42), so this matches the generator.
        K = ground_truth["camera_matrix"]
        fx = K[0, 0]
        img_w = int(K[0, 2] * 2)

        board_w = (DOT_COLS - 1) * DOT_SPACING_MM / 1000.0
        board_h = (DOT_ROWS - 1) * DOT_SPACING_MM / 1000.0
        board_centre = np.array([board_w / 2, board_h / 2, 0])

        poses = make_poses(
            10, board_centre, fx, img_w, board_w,
            fill_fraction_range=(0.80, 0.55),
        )
        rvec, tvec = poses[0]  # First view (frontal, used as datum)
        dist_coeffs = np.zeros(5)

        # Test grid points spread across the board (safely interior)
        test_points = [(3, 2), (7, 5), (11, 9), (5, 8), (10, 3)]
        errors = []

        for col, row in test_points:
            x_world_mm = col * DOT_SPACING_MM
            y_world_mm = row * DOT_SPACING_MM

            # Project to raw pixel coordinates using ground truth camera model
            obj_pt = np.array([[[col * DOT_SPACING_MM / 1000.0,
                                 row * DOT_SPACING_MM / 1000.0,
                                 0.0]]], dtype=np.float64)
            proj, _ = cv2.projectPoints(obj_pt, rvec, tvec, K, dist_coeffs)
            px, py = proj[0, 0]

            # Convert raw pixel → uncalibrated convention
            x_uncal = np.array([px + 1.0])
            y_uncal = np.array([cal.image_height - py])

            x_mm, y_mm = cal.calibrate_coordinates(x_uncal, y_uncal)

            # Polynomial output: x_mm = world_x, y_mm = -world_y
            # (Y negated: camera y-down → physical y-up)
            err_x = abs(x_mm[0] - x_world_mm)
            err_y = abs(y_mm[0] - (-y_world_mm))
            errors.append((col, row, err_x, err_y))

            assert err_x < 0.2, (
                f"Grid ({col},{row}): x_mm={x_mm[0]:.3f}, expected {x_world_mm:.1f} "
                f"(error {err_x:.3f}mm)"
            )
            assert err_y < 0.2, (
                f"Grid ({col},{row}): y_mm={y_mm[0]:.3f}, expected {-y_world_mm:.1f} "
                f"(error {err_y:.3f}mm)"
            )


