    def test_config_round_trip_calibrate_point(self, charuco_polynomial_result, ground_truth):
        """Load calibrator from config, calibrate known ChArUco corners, verify accuracy.

        Same seam test as dotboard but with ChArUco board geometry.
        ChArUco internal corners are at (col * square_size, row * square_size)
        in meters; the detector multiplies by 1000 to get mm before fitting.
        """
        config_path = charuco_polynomial_result["_config_path"]
        persist_dir = charuco_polynomial_result["_persist_dir"]
        cfg = Config(path=str(config_path))

        cal = PolynomialVectorCalibrator(
            base_dir=str(persist_dir), camera_num=1, config=cfg,
        )

        # Recompute exact poses for the ChArUco board
        K = ground_truth["camera_matrix"]
        fx = K[0, 0]
        img_w = int(K[0, 2] * 2)

        board_w = SQUARES_H * SQUARE_SIZE  # 10 * 0.030 = 0.30m
        board_h = SQUARES_V * SQUARE_SIZE  # 7 * 0.030 = 0.21m
        board_centre = np.array([board_w / 2, board_h / 2, 0])

        poses = make_poses(
            10, board_centre, fx, img_w, board_w,
            fill_fraction_range=(0.85, 0.65),
        )
        rvec, tvec = poses[0]
        dist_coeffs = np.zeros(5)

        # ChArUco internal corners: col ∈ 1..SQUARES_H-1, row ∈ 1..SQUARES_V-1
        # World coords in meters: (col * SQUARE_SIZE, row * SQUARE_SIZE, 0)
        # World coords in mm (as fitted): (col * SQUARE_SIZE * 1000, row * SQUARE_SIZE * 1000)
        sq_mm = SQUARE_SIZE * 1000.0  # 30mm

        # Test points safely interior to the board
        test_points = [(2, 2), (5, 3), (8, 5), (4, 4)]

        for col, row in test_points:
            x_world_mm = col * sq_mm
            y_world_mm = row * sq_mm

            obj_pt = np.array([[[col * SQUARE_SIZE,
                                 row * SQUARE_SIZE,
                                 0.0]]], dtype=np.float64)
            proj, _ = cv2.projectPoints(obj_pt, rvec, tvec, K, dist_coeffs)
            px, py = proj[0, 0]

            x_uncal = np.array([px + 1.0])
            y_uncal = np.array([cal.image_height - py])

            x_mm, y_mm = cal.calibrate_coordinates(x_uncal, y_uncal)

            err_x = abs(x_mm[0] - x_world_mm)
            err_y = abs(y_mm[0] - (-y_world_mm))

            assert err_x < 0.2, (
                f"Corner ({col},{row}): x_mm={x_mm[0]:.3f}, expected {x_world_mm:.1f} "
                f"(error {err_x:.3f}mm)"
            )
            assert err_y < 0.2, (
                f"Corner ({col},{row}): y_mm={y_mm[0]:.3f}, expected {-y_world_mm:.1f} "
                f"(error {err_y:.3f}mm)"
            )


